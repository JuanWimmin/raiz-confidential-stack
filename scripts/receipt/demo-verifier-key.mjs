/**
 * The DEMO disclosure-verifier key — deliberately published.
 *
 * `receipt.json` in this directory is a real selective-disclosure bundle over a
 * real testnet transfer. It is sealed to one verifier's Grumpkin public key
 * `P_R`, and only the holder of the matching secret scalar `r_R` can open it.
 * Without that scalar the committed receipt is cryptographically dead: nobody
 * cloning this repo could run `verify-receipt.mjs`, and the documented demo
 * (README §5) would fail 100% of the time. So the scalar is committed here.
 *
 * ---------------------------------------------------------------------------
 * WHY PUBLISHING THIS IS SAFE
 * ---------------------------------------------------------------------------
 * This is NOT a Stellar seed. It cannot sign a transaction, hold or move
 * funds, or authorize any contract call. It is a Grumpkin scalar generated by
 * `generateRecipientKeys()` in the vendor SDK, whose own documentation says
 * the recipient keypair is "independent of the token contract and of any
 * Stellar account"
 * (vendor/stellar-confidential-token-demo/packages/sdk/src/disclosure/recipient.ts).
 *
 * Its ONLY cryptographic power is step 6 of the SELECTIVE_DISCLOSURE.md §5.3
 * verifier protocol — `decryptDisclosure(r_R, R_disc, v~_disc, nu)` — i.e.
 * opening the amount sealed inside a disclosure bundle addressed to this P_R.
 *
 * For the committed receipt that amount is 250000000 stroops = 25 XLM, a
 * number this repository already prints in plaintext, in at least three
 * places: `scripts/receipt/README.md`, the receipt's own `claim.amountXlm`
 * field, and the project README. Publishing the key therefore reveals
 * nothing that was not already public.
 *
 * What this key does NOT unlock — none of these is derivable from it:
 *   - Marta's confidential scalar (`CT_MARTA_CONF_SK`): her balance, her
 *     viewing key, her whole transaction history. Stays secret.
 *   - The goal's auditor view key (`CT_GOAL_VIEWKEY_SECRET_HEX`). Stays
 *     secret here — though note it is published ON-CHAIN by design; that is
 *     the "el fondo es de vidrio" mechanic, unrelated to this file.
 *   - Any Stellar account seed (`CT_*_SECRET`, `GOAL_META_DEPLOYER_SECRET`).
 *   - Any OTHER receipt. A disclosure bundle is bound to a specific
 *     `(P_R, nu)` pair (§13.2 replay protection); a receipt sealed to a
 *     different verifier's key is unreadable with this one.
 *
 * ---------------------------------------------------------------------------
 * THE ONE REAL CAVEAT
 * ---------------------------------------------------------------------------
 * Because `r_R` is now public, ANY future receipt sealed to this same `P_R`
 * is readable by anyone. That is fine for a demo artifact and fatal for real
 * use. A genuine verifying party (a treasurer, an auditor, a bank desk) must
 * generate their own keypair and keep the scalar private — in production it
 * never leaves the verifying party's machine at all.
 *
 * To use your own instead of this one, set `RECEIPT_VERIFIER_SECRET_HEX` in
 * `.env.deploy` (gitignored); both scripts prefer it over this default.
 * Generate one with:
 *
 *   node -e "import('./_vendor.mjs').then(async v => \
 *     console.log('0x' + (await v).generateRecipientKeys().rR.toString(16).padStart(64,'0')))"
 *
 * ---------------------------------------------------------------------------
 * Verify for yourself that this scalar really is the one `receipt.json` is
 * sealed to — `r_R · H` must equal the receipt's `request.pR`:
 *
 *   node -e "import('./_vendor.mjs').then(async v => { \
 *     const { recipientKeysFromSecret } = await v; \
 *     const { DEMO_VERIFIER_SECRET_HEX } = await import('./demo-verifier-key.mjs'); \
 *     const k = recipientKeysFromSecret(BigInt(DEMO_VERIFIER_SECRET_HEX)); \
 *     const r = JSON.parse(require('fs').readFileSync('receipt.json','utf8')); \
 *     console.log(k.pR.x === r.request.pR.x && k.pR.y === r.request.pR.y); })"
 *
 * Expected: true.  (Checked 2026-08-04; P_R.x = 0x17a22e23a3702f77…)
 */

